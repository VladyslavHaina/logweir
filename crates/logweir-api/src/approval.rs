//! PLAT-19.2 — the console's half of ordinary confirmation and governed
//! approval (decision D0, "Ordinary versus governed approval contract").
//!
//! # What the console does, and what it never does
//!
//! After an operator's Restore create is accepted, the console builds the
//! AUTHORIZATION DOCUMENT V2 for that exact object — kind, namespace, name,
//! UID, the plan hash, the requester it authenticated, the namespace's bound
//! policy name and snapshot digest, an issue time and an expiry no later than
//! the policy's `maxAgeSeconds` — and signs it with its `ConsoleConfirmation`
//! key. That signature attests ONE thing: which authenticated principal asked.
//!
//! * **Ordinary**: the signed document is the whole authorization, stored as
//!   the `Approval` the Restore references.
//! * **Governed**: the signed document is stored as a CONFIRMATION object
//!   (`<approvalRef>-confirmation`) that authorises nothing; an approver
//!   countersigns the same bytes and submits them, and only then does the
//!   referenced `Approval` exist.
//! * **Unbound** (`legacy-governed-v1`): nothing is signed. The Restore waits
//!   for today's v1 approval exactly as before.
//!
//! The controller is the final gate (D0): it re-verifies the console's
//! signature against the namespace's `TrustPolicy`, the policy digest against
//! its own copy of the same installation document, and — under Governed — the
//! approver's signature and principal. Nothing here is trusted by the
//! controller that it does not re-derive.
//!
//! # The key
//!
//! A PKCS#8 PEM file, mounted from a Secret. It is never logged, never
//! serialised, never in a response; only its key id and public half are
//! published, so an administrator can add the public half to the namespace's
//! `TrustPolicy` with usage `ConsoleConfirmation`. A `ConsoleConfirmation` key
//! can never verify evidence (D3 §7.3, `weirkeeper::verification`), so holding
//! it gives this service no evidence signing capability — which is why
//! linking the signer here is recorded in `scripts/check-one-signer.sh`
//! rather than slipped in.
//!
//! PROD-16.1: the chart's MANAGED key (`logweir-console-confirmation`) is
//! generated by the identity hook, which Helm runs AFTER this pod starts. A
//! configured key file that does not exist yet is therefore not a startup
//! refusal: it is read the first time a confirmation needs it, and until then
//! every request that would need it is refused before anything is created. A
//! file that exists and does not parse is still a refusal to start.
//!
//! # The fresh-install marker (PROD-16.1)
//!
//! An unbound namespace resolves to `confirm` on a fresh install. That fact is
//! a claim the identity hook writes, in the run that generated the identity,
//! on the installation's public identity ConfigMap
//! (`logweir.dev/approval-default`), naming the default `TrustPolicy` the same
//! run created. [`effective_policies`] reads both on every request that
//! resolves a policy and honours the claim only through
//! `weirkeeper::approval_policy::marker_verdict` — the verdict the controller
//! reaches over the same objects — so the two cannot disagree and an
//! annotation patched into an older install changes nothing. An absent
//! object, annotation or policy is unmarked: `legacy-governed-v1`.
//!
//! # Two-person approval in the console (PROD-16.2)
//!
//! Under a policy whose `approverSignature` is `Console` the second person
//! signs in and clicks Approve, and THIS key signs the approval too. One key,
//! two documents, so what stops the console being talked into approving a
//! request it never confirmed is the order in [`verified_request`] and the
//! route that calls it:
//!
//! 1. the stored request's sidecar must carry a signature by THIS console's
//!    key that verifies over the stored bytes — and until it does, nothing of
//!    the object is read for any other purpose (not its annotations, not its
//!    labels, not `spec.planHash`, not `spec.subjectRef`);
//! 2. the verified bytes, parsed, must bind the Restore the click names (its
//!    namespace, name, current UID and the hash of its current plan bytes)
//!    and the namespace's CURRENT policy, and must not have expired
//!    (`logweir_core::approval_policy::check_request_binding`) — so a
//!    signature lifted from another request binds another request;
//! 3. the approval is that verified document with `approver`, `approvedAt`
//!    and the 2.2.0 version added ([`approved_document`]) — every other field
//!    is the verified one, re-serialised by the one writer.
//!
//! The console never signs an approval over bytes it did not first verify
//! under its own key, and it signs a REQUEST only for the principal of the
//! session that created the Restore. What that leaves is stated in
//! `SECURITY.md`: whoever holds this key, controls this pod, or controls the
//! identity provider can produce both documents alone.

