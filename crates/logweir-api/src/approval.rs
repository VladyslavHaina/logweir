/// The suffix of a governed request's confirmation object.
pub const CONFIRMATION_SUFFIX: &str = "-confirmation";

/// The longest `approvalRef.name` whose confirmation name still fits the
/// 253-character object-name limit.
pub const MAX_GOVERNED_APPROVAL_NAME: usize = 253 - CONFIRMATION_SUFFIX.len();

/// The confirmation object's name for a governed request.
#[must_use]
pub fn confirmation_name(approval_name: &str) -> String {
    format!("{approval_name}{CONFIRMATION_SUFFIX}")
}

/// The annotation on a request object naming who signed in when it was made:
/// `<issuer>#<subject>`. Written beside the signed bytes, never read for a
/// decision.
pub const REQUESTER_ANNOTATION: &str = "logweir.dev/requester";

/// DUI-21: the annotation holding the [`RequesterDisplay`] document's exact
/// bytes, and the one holding this console's signature over them
/// ([`PAYLOAD_TYPE_REQUESTER_DISPLAY`]). An annotation anyone who may patch
/// Approvals can change, so its content is served only when that signature
/// verifies and the document binds this very request ([`verified_display`]).
pub const REQUESTER_DISPLAY_ANNOTATION: &str = "logweir.dev/requester-display";
/// See [`REQUESTER_DISPLAY_ANNOTATION`].
pub const REQUESTER_DISPLAY_SIGNATURE_ANNOTATION: &str = "logweir.dev/requester-display-signature";

/// The DSSE payload type of a [`RequesterDisplay`]. Not the request's: the
/// console key's signature over one never verifies as the other.
pub const PAYLOAD_TYPE_REQUESTER_DISPLAY: &str = "application/vnd.logweir.requester-display+json";

/// The document's `kind`.
pub const REQUESTER_DISPLAY_KIND: &str = "RequesterDisplay";

/// The longest email an identifier may be (RFC 5321's path limit).
pub const MAX_EMAIL_BYTES: usize = 254;

/// **What an approver is shown about who asked, signed by the console**
/// (DUI-21, second security review). Bound to one request by its approval
/// name, the requester principal exactly as the signed request names it, and
/// the plan hash; the email only when the provider verified it and it has an
/// identifier's shape ([`email_shape_ok`]), the name only from a claim the
/// install opted into, cleaned ([`shown_name`]).
#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct RequesterDisplay {
    /// [`REQUESTER_DISPLAY_KIND`].
    pub kind: String,
    /// The Approval the subject references.
    pub approval_name: String,
    /// `<issuer>#<subject>`, as the signed request's requester.
    pub requester: String,
    /// The signed request's plan hash.
    pub plan_hash: String,
    /// The provider-verified email.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub email: Option<String>,
    /// The name from an opted-in claim: self-asserted.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,
}

/// **Whether an email may be shown as an identifier, exactly as received**:
/// printable ASCII with no whitespace, at most [`MAX_EMAIL_BYTES`], and of
/// the form `local@domain` (one `@`, neither side empty). An identifier is
/// never normalised or cut: an address that fails is not shown at all, and
/// the principal is used, so two different addresses can never render alike.
#[must_use]
pub fn email_shape_ok(raw: &str) -> bool {
    raw.len() <= MAX_EMAIL_BYTES
        && raw.bytes().all(|b| b.is_ascii_graphic())
        && matches!(
            raw.split_once('@'),
            Some((local, domain)) if !local.is_empty() && !domain.is_empty() && !domain.contains('@')
        )
}

/// Build and sign the display document for one request, or `None` when there
/// is nothing to show beyond the signed principal. Returns the document's
/// exact bytes and the sidecar, for the two annotations.
///
/// # Errors
///
/// When the signer fails.
pub fn requester_display(
    key: &ConfirmationKey,
    approval_name: &str,
    requester: &str,
    plan_hash: &str,
    email: Option<&str>,
    name: Option<&str>,
) -> Result<Option<(String, String)>, String> {
    let email = email.filter(|e| email_shape_ok(e)).map(str::to_string);
    let name = name.and_then(shown_name);
    if email.is_none() && name.is_none() {
        return Ok(None);
    }
    let document = RequesterDisplay {
        kind: REQUESTER_DISPLAY_KIND.to_string(),
        approval_name: approval_name.to_string(),
        requester: requester.to_string(),
        plan_hash: plan_hash.to_string(),
        email,
        name,
    };
    let bytes = serde_json::to_string(&document)
        .map_err(|e| format!("rendering the display document: {e}"))?;
    let sidecar = sign_detached(&key.key, PAYLOAD_TYPE_REQUESTER_DISPLAY, bytes.as_bytes())
        .map_err(|e| format!("signing the display document: {e}"))?;
    let sidecar = serde_json::to_string(&sidecar)
        .map_err(|e| format!("rendering the display sidecar: {e}"))?;
    Ok(Some((bytes, sidecar)))
}

/// What a request object may show of its requester beyond the signed
/// principal.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum DisplayCheck {
    /// The object carries no display document (a request made before them, or
    /// one with nothing to show): the signed principal alone.
    Absent,
    /// The console's own signature verifies over a document binding THIS
    /// request; its email (shape held again) and name may be shown.
    Verified {
        /// The provider-verified email.
        email: Option<String>,
        /// The opted-in, self-asserted name.
        name: Option<String>,
    },
    /// A document is there and it does not verify, or binds another request:
    /// nothing of it is shown, and the page says so.
    NotVerified,
}

/// **The display document of a request, served only if the console signed
/// it for this request.** The signature must verify under this console's key
/// and the display payload type; the document must parse (no unknown field),
/// be a [`REQUESTER_DISPLAY_KIND`], and name exactly `requester` (the signed
/// request's), `approval_name` and `plan_hash`; its email must still have an
/// identifier's shape. Anything else is [`DisplayCheck::NotVerified`].
#[must_use]
pub fn verified_display(
    key: &ConfirmationKey,
    annotations: &std::collections::BTreeMap<String, String>,
    requester: &str,
    approval_name: &str,
    plan_hash: &str,
) -> DisplayCheck {
    let document = annotations.get(REQUESTER_DISPLAY_ANNOTATION);
    let signature = annotations.get(REQUESTER_DISPLAY_SIGNATURE_ANNOTATION);
    let (Some(document), Some(signature)) = (document, signature) else {
        return if document.is_none() && signature.is_none() {
            DisplayCheck::Absent
        } else {
            DisplayCheck::NotVerified
        };
    };
    let Ok(sidecar) = serde_json::from_str::<Sidecar>(signature) else {
        return DisplayCheck::NotVerified;
    };
    if logweir_evidence::verify::verify_detached(
        &key.key.verifying_key(),
        PAYLOAD_TYPE_REQUESTER_DISPLAY,
        document.as_bytes(),
        &sidecar,
    )
    .is_err()
    {
        return DisplayCheck::NotVerified;
    }
    let Ok(display) = serde_json::from_str::<RequesterDisplay>(document) else {
        return DisplayCheck::NotVerified;
    };
    let binds = display.kind == REQUESTER_DISPLAY_KIND
        && display.requester == requester
        && display.approval_name == approval_name
        && display.plan_hash == plan_hash
        && display.email.as_deref().is_none_or(email_shape_ok);
    if !binds {
        return DisplayCheck::NotVerified;
    }
    DisplayCheck::Verified {
        email: display.email,
        name: display.name.as_deref().and_then(shown_name),
    }
}

/// The most characters a shown name keeps.
pub const MAX_SHOWN_NAME_CHARS: usize = 128;

/// A character that changes how text around it is displayed without being
/// visible itself: the bidirectional controls and isolates, the zero-width
/// characters, the byte-order mark, the Arabic letter mark and the soft
/// hyphen. A name shown to another person must not reorder or hide what sits
/// beside it.
fn is_invisible_format(c: char) -> bool {
    matches!(
        c,
        '\u{00AD}'
            | '\u{061C}'
            | '\u{180E}'
            | '\u{200B}'..='\u{200F}'
            | '\u{202A}'..='\u{202E}'
            | '\u{2060}'..='\u{2064}'
            | '\u{2066}'..='\u{2069}'
            | '\u{FEFF}'
    )
}

/// **A name as it may be shown to another person** (DUI-21): control and
/// invisible formatting characters removed, any run of whitespace one space,
/// the ends trimmed, and at most [`MAX_SHOWN_NAME_CHARS`] characters (a cut
/// name ends with `…`). `None` when nothing printable is left.
#[must_use]
pub fn shown_name(raw: &str) -> Option<String> {
    let mut out = String::new();
    let mut space = false;
    for c in raw.chars() {
        if is_invisible_format(c) {
            continue;
        }
        if c.is_whitespace() || c.is_control() {
            space = !out.is_empty();
            continue;
        }
        if space {
            out.push(' ');
            space = false;
        }
        out.push(c);
    }
    if out.is_empty() {
        return None;
    }
    if out.chars().count() > MAX_SHOWN_NAME_CHARS {
        let cut: String = out.chars().take(MAX_SHOWN_NAME_CHARS - 1).collect();
        return Some(format!("{}…", cut.trim_end()));
    }
    Some(out)
}

/// The console's `ConsoleConfirmation` signing key.
pub struct ConfirmationKey {
    key: SigningKey,
    key_id: String,
    public_pem: String,
}

impl std::fmt::Debug for ConfirmationKey {
    /// THE PRIVATE HALF IS NEVER FORMATTED. Only the key id, which is public.
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("ConfirmationKey")
            .field("key_id", &self.key_id)
            .finish_non_exhaustive()
    }
}

impl ConfirmationKey {
    /// Read a PKCS#8 PEM private key file.
    ///
    /// # Errors
    ///
    /// A reason naming the PATH, never the contents.
    pub fn from_file(path: &Path) -> Result<Self, String> {
        let key = SigningKey::from_pem_file(path).map_err(|e| {
            format!(
                "cannot read the console confirmation key {}: {e}",
                path.display()
            )
        })?;
        Self::from_key(key)
    }

    /// Wrap an in-memory key (tests, and the file loader above).
    ///
    /// # Errors
    ///
    /// When the public half cannot be rendered.
    pub fn from_key(key: SigningKey) -> Result<Self, String> {
        let public_pem = key
            .verifying_key()
            .to_public_key_pem()
            .map_err(|e| format!("cannot render the confirmation key's public half: {e}"))?;
        Ok(Self {
            key_id: key.key_id(),
            key,
            public_pem,
        })
    }

    /// The key id an administrator puts on the `TrustPolicy`.
    #[must_use]
    pub fn key_id(&self) -> &str {
        &self.key_id
    }

    /// The public half, SPKI PEM.
    #[must_use]
    pub fn public_pem(&self) -> &str {
        &self.public_pem
    }

    /// Sign exact document bytes under the v2 payload type.
    ///
    /// # Errors
    ///
    /// When the signer fails.
    pub fn sign(&self, document: &[u8]) -> Result<Sidecar, String> {
        sign_detached(&self.key, PAYLOAD_TYPE_RESTORE_AUTHORIZATION, document)
            .map_err(|e| format!("signing the authorization document: {e}"))
    }

    /// **Whether THIS key signed exactly these bytes** -- the
    /// console verifying its own earlier `ConsoleConfirmation` signature.
    ///
    /// The sidecar must be a v2 sidecar and carry a signature under this
    /// key's id that verifies over `document` (DSSE PAE, so the payload type
    /// is inside what is verified). A signature by any other key, however
    /// trusted elsewhere, is not this console's confirmation.
    ///
    /// # Errors
    ///
    /// The verifier's reason. Never the document.
    pub fn verifies(&self, document: &[u8], sidecar: &Sidecar) -> Result<(), String> {
        logweir_evidence::verify::verify_detached(
            &self.key.verifying_key(),
            PAYLOAD_TYPE_RESTORE_AUTHORIZATION,
            document,
            sidecar,
        )
        .map(|_| ())
        .map_err(|e| e.to_string())
    }
}

/// A stored request this console verified its own signature on, and the
/// identity of the bytes it verified.
#[derive(Clone, Debug)]
pub struct VerifiedRequest {
    /// The document, parsed from the VERIFIED bytes and from nothing else.
    pub document: RestoreAuthorization,
    /// `sha256:<hex>` of those bytes: what the approver's view shows and the
    /// click must repeat.
    pub sha256: String,
}

/// **The console verifies its OWN earlier signature on a
/// stored request, before anything else is done with it.**
///
/// Takes the two byte strings of the stored object and nothing else of it —
/// by signature, this function CANNOT read an annotation, a label,
/// `spec.planHash` or `spec.subjectRef`. The document it returns is parsed
/// from the bytes the signature covers, after the signature verified.
///
/// # Errors
///
/// A sentence saying the request is not this console's confirmation. It
/// names the key id (public) and never echoes the stored text.
pub fn verified_request(
    key: &ConfirmationKey,
    approval_bytes: &str,
    sidecar_bytes: &str,
) -> Result<VerifiedRequest, String> {
    let sidecar: Sidecar = serde_json::from_str(sidecar_bytes).map_err(|_| {
        "the stored request's sidecar is not a DSSE sidecar, so it carries no signature of this \
         console's"
            .to_string()
    })?;
    key.verifies(approval_bytes.as_bytes(), &sidecar)
        .map_err(|reason| {
            format!(
                "the stored request does not carry a signature by this console's confirmation \
                 key {} over its bytes ({reason}); the console approves only a request it \
                 confirmed itself",
                key.key_id()
            )
        })?;
    let document =
        RestoreAuthorization::from_bytes(approval_bytes.as_bytes()).map_err(|e| e.to_string())?;
    Ok(VerifiedRequest {
        document,
        sha256: logweir_core::ids::sha256_prefixed(approval_bytes.as_bytes()),
    })
}

/// **The approval of a verified request** -- that
/// document with exactly three changes: `approver`, `approvedAt`, and the
/// version the one writer gives a document that carries them (2.2.0).
///
/// Requester, subject, UID, plan hash, policy, `issuedAt`, `expiresAt`, the
/// ticket and the approval subject are the VERIFIED request's: this function
/// takes no other source for them.
#[must_use]
pub fn approved_document(
    request: &RestoreAuthorization,
    approver: Approver,
    approved_at: DateTime<Utc>,
) -> RestoreAuthorization {
    RestoreAuthorization {
        format_version: logweir_core::approval_policy::RESTORE_AUTHORIZATION_FORMAT_VERSION
            .to_string(),
        approver: Some(approver),
        approved_at: Some(approved_at),
        ..request.clone()
    }
}

